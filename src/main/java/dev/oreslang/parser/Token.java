package dev.oreslang.parser;

public record Token(Type type, String lexeme, int line, int column) {
    public enum Type {
        IDENT,
        INT,
        FLOAT,
        IMAG,
        STRING,

        DEFINE, CLASS, MODULE, NAMESPACE, IMPORT, FROM, AS, IS, EXTENDS, IMPLEMENTS,
        TRY, CATCH, FINALLY, END, FI, IF, DO, ELSE, THEN,
        NEW, STOP, DONE, AWAIT, ASYNC, DEF, FNC, ROUTINE, FOR, OF, YIELD, SUPER, ELSEIF, SWITCH, TYPE, TYPEOF,
        INTERFACE, IMPL, ABSTRACT, VOID, STATIC, PUB, PRIVATE, STRUCTURAL, RETURN, DEFER, BREAK, CONTINUE,
        ACTOR, ISOLATE, RECOVER, PANIC,
        VAL, CONST, LET, MUT, SELF, TRUE, FALSE, NULL, OBJ, ARR,

        LPAREN, RPAREN, LBRACE, RBRACE, LBRACKET, RBRACKET,
        COMMA, DOT, SEMICOLON, COLON, QUESTION, AT,
        PLUS, MINUS, STAR, SLASH, PERCENT, PIPE, AMP, BANG,
        EQUAL, EQUAL_EQUAL, BANG_EQUAL,
        LT, LTE, GT, GTE,
        ARROW, FAT_ARROW,
        EOF
    }
}
